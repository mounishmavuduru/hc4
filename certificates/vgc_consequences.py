banner('A1  det[[H,g],[g^T,0]] = -g^T adj(H) g            n = 2,3,4   (PROOF)')
for n in (2, 3, 4):
    H = symH(n, f'h{n}_')
    g = sp.Matrix(sp.symbols(f'g{n}_0:{n}'))
    M = sp.zeros(n + 1, n + 1)
    M[:n, :n] = H
    M[:n, n] = g
    M[n, :n] = g.T
    assert sp.expand(M.det(method='berkowitz') + (g.T * H.adjugate() * g)[0, 0]) == 0
    print(f'  n={n}: PROVED')

banner('A2  det Hess_{n+1}(y e + f): degree <= n-1 in y, top coefficient -B(e)   (PROOF)')
for n in (2, 3):
    He, Hf = symH(n, f'p{n}_'), symH(n, f'q{n}_')
    g = sp.Matrix(sp.symbols(f'r{n}_0:{n}'))
    M = sp.zeros(n + 1, n + 1)
    M[:n, :n] = y * He + Hf
    M[:n, n] = g
    M[n, :n] = g.T
    D = sp.expand(M.det(method='berkowitz'))
    assert sp.expand(D + (g.T * (y * He + Hf).adjugate() * g)[0, 0]) == 0
    P = sp.Poly(D, y)
    assert P.degree() <= n - 1
    assert sp.expand(P.coeff_monomial(y**(n - 1)) + (g.T * He.adjugate() * g)[0, 0]) == 0
    print(f'  n={n}: det Hess(y e + f) = -g^T adj(yH_e + H_f) g, [y^(n-1)] = -B(e)   PROVED')
for n in (2, 3, 4):
    H = symH(n, f'u{n}_')
    g = sp.Matrix(sp.symbols(f'w{n}_0:{n}'))
    M = sp.zeros(n + 1, n + 1)
    M[:n, :n] = y * H
    M[:n, n] = g
    M[n, :n] = g.T
    assert sp.expand(M.det(method='berkowitz') + y**(n - 1) * (g.T * H.adjugate() * g)[0, 0]) == 0
    print(f'  n={n}: det Hess_(n+1)(y e(x)) = -y^(n-1) B(e)                          PROVED')
print('  => Theorem G <=> [det Hess(y e(x)) == 0 => det Hess e == 0]; Corollary LV.')

banner("A3  Jacobian of (e, [grad e]):  det J' = g_n^(n-2) B(e)     n = 2,3,4   (PROOF)")
for n in (2, 3, 4):
    H = symH(n, f'a{n}_')
    g = sp.Matrix(sp.symbols(f'b{n}_0:{n}'))
    rows = []
    for i in range(n - 1):
        rows.append([g[n - 1] * H[i, j] - g[i] * H[n - 1, j] for j in range(n)])
    rows.append([g[j] for j in range(n)])
    Jp = sp.Matrix(rows)
    B = sp.expand((g.T * H.adjugate() * g)[0, 0])
    assert sp.expand(Jp.det(method='berkowitz') - g[n - 1]**(n - 2) * B) == 0, n
    print(f'  n={n}: det[ g_n H_i - g_i H_n (i<n) ; g^T ] = g_n^(n-2) * B          PROVED')
# polynomial-level confirmation on an instance: rank of Jac(e, g1/g3, g2/g3)
