print('  => B(e) == 0 <=> (e,[grad e]) not dominant <=> e algebraic over C(g_i/g_n).')

banner('A4  Dolgachev affine equation of the Hessian + pencil version   (PROOF)')
for (n, d) in ((2, 2), (2, 3), (2, 4), (3, 2), (3, 3)):
    vs = X[n]
    e = gen_poly(vs, d, f'e{n}{d}_')
    E = homog(e, vs, d)
    lhs = sp.expand(dethess(E, (x0,) + tuple(vs)).subs(x0, 1))
    rhs = sp.expand(d * (d - 1) * e * dethess(e, vs) - (d - 1)**2 * Bof(e, vs))
    assert sp.expand(lhs - rhs) == 0, (n, d)
    # pencil version with a free c
    Ec = sp.expand(E - c * x0**d)
    lhs_c = sp.expand(dethess(Ec, (x0,) + tuple(vs)).subs(x0, 1))
    rhs_c = sp.expand(d * (d - 1) * (e - c) * dethess(e, vs) - (d - 1)**2 * Bof(e, vs))
    assert sp.expand(lhs_c - rhs_c) == 0, (n, d, 'pencil')
    print(f'  n={n}, d={d}: identity and pencil identity (free c)                  PROVED')
